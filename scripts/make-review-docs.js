// npm run review-docs: generates the practitioner copy review documents (review/<section>.md)
// from the content files in src/content/<section>/. Per page: front matter fields as published,
// the full body copy, FAQs, open [[TODO]] placeholders, and a "Facts to confirm" checklist.
// The checklist = facts reported by the copy writers (scripts/data/facts-to-confirm.json)
// plus the facts strip values and TODOs found in the page. Nothing is rewritten by hand.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SECTIONS = { aesthetics: "Aesthetics", facials: "Facials", beauty: "Beauty" };
const facts = JSON.parse(fs.readFileSync(path.join(root, "scripts/data/facts-to-confirm.json"), "utf8"));
const sections = JSON.parse(fs.readFileSync(path.join(root, "src/_data/sections.json"), "utf8"));
const services = JSON.parse(fs.readFileSync(path.join(root, "src/_data/services.json"), "utf8"));
const byId = new Map(services.map((s) => [String(s.id), s]));

const todosIn = (text) => [...new Set(text.match(/\[\[TODO[^\]]*\]\]/g) ?? [])];
const order = (key) => {
  const pages = sections[key]?.pages ?? [];
  return (slug) => { const i = pages.findIndex((p) => p.slug === slug); return i === -1 ? -1 : i; };
};

fs.mkdirSync(path.join(root, "review"), { recursive: true });
const today = new Date().toISOString().slice(0, 10);

for (const [key, label] of Object.entries(SECTIONS)) {
  const dir = path.join(root, "src/content", key);
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md"));
  const pages = files.map((f) => {
    const { data, content } = matter(fs.readFileSync(path.join(dir, f), "utf8"));
    return { file: f, slug: data.slug ?? f.replace(/\.md$/, ""), data, body: content.trim() };
  }).filter((p) => p.data.permalink !== false); // pages taken off the site are left out
  const pos = order(key);
  pages.sort((a, b) => (a.file === "index.md" ? -1 : b.file === "index.md" ? 1 : pos(a.slug) - pos(b.slug)));

  const out = [];
  out.push(`# ${label}: copy review`);
  out.push("");
  out.push(`Generated ${today} by scripts/make-review-docs.js from src/content/${key}/. Do not edit this file: change the content files and regenerate.`);
  out.push("");
  out.push("**How to review:** read each page, tick or correct each item under *Facts to confirm*, and mark anything that is wrong or missing. Text in [[TODO: ...]] is information we do not have yet. Words like \"typically\" mark a general statement that needs your agreement. Prices are not shown here: they come from the booking system.");
  out.push("");
  if (key === "aesthetics") {
    out.push("**Prescriber sign-off needed on every aesthetics page before launch.** Prescription medicines are never named on the site: the consultation page is the only entry point for them.");
    out.push("");
  }
  const generalFacts = facts[key]?._general ?? [];
  if (generalFacts.length) {
    out.push("## Section-wide checks", "");
    generalFacts.forEach((f) => out.push(`- [ ] ${f}`));
    out.push("");
  }
  out.push("## Contents", "");
  pages.forEach((p, i) => out.push(`${i + 1}. ${p.data.title}${p.file === "index.md" ? " (hub)" : ""}`));
  out.push("");

  const allTodos = [];
  for (const p of pages) {
    const d = p.data;
    out.push("---", "", `## ${d.title}${p.file === "index.md" ? " (hub)" : ""}`, "");
    out.push(`- **URL:** /${key}/${p.file === "index.md" ? "" : p.slug + "/"}`);
    out.push(`- **Page title (search results):** ${d.metaTitle}`);
    out.push(`- **Description (search results):** ${d.metaDescription}`);
    if (d.practitioner) out.push(`- **Practitioner shown:** ${d.practitioner}`);
    if (d.bookLabel) out.push(`- **Book button:** ${d.bookLabel}`);
    if (d.services?.length) {
      const names = d.services.map((id) => byId.get(String(id))?.publicName ?? `[unknown service ${id}]`);
      out.push(`- **Booking menu entries linked:** ${[...new Set(names)].join("; ")}`);
    }
    if (d.facts) out.push(`- **Quick facts:** ${Object.entries(d.facts).map(([k, v]) => `${k}: ${v}`).join(" | ")}`);
    out.push("");
    out.push("### Introduction", "", d.lead, "");
    if (d.notSure) out.push("### Not sure which treatment is right for you?", "", `**${d.notSure.title}**`, "", d.notSure.text, "");
    if (p.body) out.push("### Page copy", "", p.body.replace(/^## /gm, "#### "), "");
    if (d.faqs?.length) {
      out.push("### Questions and answers", "");
      d.faqs.forEach((f) => out.push(`**${f.q}**`, "", f.a, ""));
    }
    if (d.related?.length) out.push(`*Related pages shown:* ${d.related.join(", ")}`, "");

    const raw = JSON.stringify(d) + p.body;
    const todos = todosIn(raw);
    // The page shows "Price on consultation" for held-back prices; the open decision stays visible here.
    if ((d.services ?? []).some((id) => { const x = byId.get(String(id)); return x && !x.isPrescription && !x.pricePublic; })) todos.push("[[TODO: price held back until Yemi decides; the page shows \"Price on consultation\" meanwhile]]");
    todos.forEach((t) => allTodos.push({ page: d.title, todo: t }));
    out.push("### Facts to confirm", "");
    const list = facts[key]?.[p.file === "index.md" ? "index" : p.slug] ?? [];
    if (!list.length) out.push("- [ ] (no specific facts reported for this page: confirm the copy reads correctly)");
    list.forEach((f) => out.push(`- [ ] ${f}`));
    todos.forEach((t) => out.push(`- [ ] Open placeholder: ${t}`));
    out.push("");
  }

  out.push("---", "", "## All open placeholders in this section", "");
  if (!allTodos.length) out.push("None.");
  allTodos.forEach((t) => out.push(`- **${t.page}:** ${t.todo}`));
  out.push("");
  const file = path.join(root, "review", `${key}.md`);
  fs.writeFileSync(file, out.join("\n"));
  console.log(`review/${key}.md: ${pages.length} pages, ${allTodos.length} placeholders`);
}
