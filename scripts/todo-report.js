// npm run todo: scans the built site (_site) for every [[TODO...]] placeholder and writes TODO.md,
// grouped by who supplies it (Yemi, practitioners and the prescriber, legal review), plus the launch checklist.
// Placeholders on /styleguide/ and /404.html are ignored. Run `npm run build` first.
// The checklist and the "not a placeholder" items are edited by hand in the CHECKLIST and EXTRA blocks below.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const siteDir = path.join(root, "_site");
if (!fs.existsSync(siteDir)) { console.error("todo-report: _site not found. Run npm run build first."); process.exit(1); }

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (e.name.endsWith(".html")) out.push(p);
  }
  return out;
};
const unesc = (s) => s.replace(/<[^>]*>/g, "").replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/\s+/g, " ").trim();

// text -> { pages:Set }
const found = new Map();
for (const f of walk(siteDir)) {
  const url = "/" + path.relative(siteDir, f).split(path.sep).join("/").replace(/index\.html$/, "");
  if (url === "/styleguide/" || url === "/404.html") continue;
  const html = fs.readFileSync(f, "utf8");
  for (const m of html.matchAll(/\[\[TODO(?::\s*)?([^\]]*)\]\]/g)) {
    const text = unesc(m[1]) || "ICO registration number (About page and privacy notice)";
    if (!found.has(text)) found.set(text, new Set());
    found.get(text).add(url);
  }
}

const LEGAL = /legal review|retention|international transfer|data processing|which cookies|cookies .*booking panel|limitation of liability/i;
const PRACT = /practitioner (to|’s|'s)|from the practitioner|, from the practitioner|for the practitioner|prescriber to|product|what each|what the .* (include|involve)|how (comcit|long to pause)|steps and peel|reasons .* not be suitable|course length|make-up after|massage the treated|treatment can follow|usual number of sessions|lead time|1ml filler|filler review|age policy|18\+ policy/i;
const group = (t) => (LEGAL.test(t) ? "legal" : PRACT.test(t) && !/^Yemi (to|and the prescriber to) confirm the (salon|age)/i.test(t) ? "pract" : "yemi");

const buckets = { yemi: [], pract: [], legal: [] };
for (const [text, pages] of found) buckets[group(text)].push({ text, pages: [...pages].sort() });

// Collapse the many per-page review placeholders and card photos into one line each.
const collapse = (items) => {
  const out = []; const reviews = []; const photos = []; const practRoles = []; const cardNames = [];
  for (const it of items) {
    if (/^one to three (Phorest|general salon) reviews/.test(it.text)) { reviews.push(it); continue; }
    if (/^photo: card for/.test(it.text)) { photos.push(it); continue; }
    if (/^Yemi to supply every practitioner|^practitioner (name|first name)$|^role, training and registration$|^role and training$|^role$|^registering body|^link to the register|^qualifications and training$|^professional indemnity|^treatments performed or prescribed by this practitioner$|^practitioner name, role and registration/.test(it.text)) { practRoles.push(it); continue; }
    out.push(it);
  }
  if (reviews.length) out.unshift({ text: `One to three real reviews per treatment page, as first name and surname initial plus month and year (${reviews.length} placeholders; none may mention injections, lines and wrinkles results or any medicine). Also the three review cards on the home page and the review text, name and month fields`, pages: [...new Set(reviews.flatMap((r) => r.pages))].sort() });
  if (photos.length) out.push({ text: `Card photos for ${photos.length} treatments still on a placeholder (${photos.map((p) => p.text.replace("photo: card for ", "")).join(", ")})`, pages: [...new Set(photos.flatMap((r) => r.pages))].sort() });
  if (practRoles.length) out.unshift({ text: "Practitioner details for every practitioner card (name, role, photo, registering body and number, link to the register entry, training, indemnity insurance, treatments performed or prescribed). Add once to src/_data/practitioners.json and every card fills in", pages: [...new Set(practRoles.flatMap((r) => r.pages))].sort() });
  return out;
};

const fmtPages = (pages) => (pages.length > 4 ? `${pages.slice(0, 3).join(", ")} and ${pages.length - 3} more` : pages.join(", "));
const list = (items) => items.map((it) => `- [ ] ${it.text.charAt(0).toUpperCase() + it.text.slice(1)} \`${fmtPages(it.pages)}\``).join("\n");

const total = [...found.values()].reduce((n, s) => n + s.size, 0);
const distinct = found.size;

